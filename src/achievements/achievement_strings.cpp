// XLanguage values (the console's, as `user_language` holds them) to the
// table's columns; anything else is English, as the title shows it.
Language Current() {
  static const Language language = [] {
    switch (std::atoi(rex::cvar::GetFlagByName("user_language").c_str())) {
      case 2: return kJa;
      case 3: return kDe;
      case 4: return kFr;
      case 5: return kEs;
      case 6: return kIt;
      case 7: return kKo;
      case 8: return kZh;
      case 9: return kPt;
      case 11: return kPl;
      case 12: return kRu;
      case 13: return kSv;
      case 15: return kNb;
      case 16: return kNl;
      default: return kEn;
    }
  }();
  return language;
}

