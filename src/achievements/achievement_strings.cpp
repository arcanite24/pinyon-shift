std::string_view Tr(Text text) {
  return size_t(text) < kStrings.size() ? kStrings[size_t(text)][Current()] : std::string_view();
}

std::string Format(Text text, std::initializer_list<std::string_view> args) {
  const std::string_view pattern = Tr(text);
  std::string out;
  for (size_t i = 0; i < pattern.size(); ++i) {
    if (pattern[i] == '{' && i + 2 < pattern.size() && pattern[i + 2] == '}' &&
        pattern[i + 1] >= '0' && size_t(pattern[i + 1] - '0') < args.size()) {
      out += *(args.begin() + (pattern[i + 1] - '0'));
      i += 2;
    } else {
      out += pattern[i];
    }
  }
  return out;
}

std::string FormatDate(int year, int month, int day) {
  static constexpr const char* kMonths[] = {"JAN", "FEB", "MAR", "APR", "MAY", "JUN",
                                            "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"};
  const std::string y = std::to_string(year), m = std::to_string(month), d = std::to_string(day);
  const auto two = [](int value) { return (value < 10 ? "0" : "") + std::to_string(value); };
  switch (Current()) {
    case kEn: return d + " " + kMonths[(month + 11) % 12] + " " + y;
    case kJa:
    case kZh: return y + "年" + m + "月" + d + "日";
    case kKo: return y + "년 " + m + "월 " + d + "일";
    case kDe:
    case kPl:
    case kRu:
    case kNb: return two(day) + "." + two(month) + "." + y;
    case kSv: return y + "-" + two(month) + "-" + two(day);
    case kNl: return two(day) + "-" + two(month) + "-" + y;
    default: return two(day) + "/" + two(month) + "/" + y;  // fr, es, it, pt
  }
}

std::string_view CategoryName(Category category) {
  static constexpr Text kNames[] = {Text::kCareer, Text::kRacing,   Text::kFame,
                                    Text::kExplore, Text::kFestival, Text::kOnline,
                                    Text::kRally,  Text::kClub};
  return size_t(category) < std::size(kNames) ? Tr(kNames[size_t(category)]) : std::string_view();
}

std::string_view BandName(int index) {
  return index >= 0 && index < 7 ? Tr(Text(size_t(Text::kYellow) + size_t(index)))
                                 : std::string_view();
}

